/**
 * ⚠️ NEVER EDIT A MIGRATION PRODUCTION HAS ALREADY APPLIED. Put the fix in a new timestamped
 * migration. This script is what makes that rule findable instead of remembered: it recomputes
 * every file's body md5 and compares it against what `supabase_migrations.schema_migrations`
 * recorded when the statement actually ran.
 *
 * ⚠️ THE RECORD IS COMMITTED, NOT FETCHED, AND THAT IS DELIBERATE. CI has no database
 * credentials and must never be given any — `docs/ci/db-guards.yml` says why at length. So the
 * production side of the comparison lives in `supabase/migrations/applied.md5`, regenerated by
 * hand from the query in that file's header. The cost of that choice is honest: somebody who
 * edits a migration AND re-records the manifest passes this check. What they cannot do is edit a
 * migration quietly — the manifest line moves in the same diff, under a column named for it.
 *
 * ── THE BODY RULE, MEASURED RATHER THAN ASSUMED ───────────────────────────────────────────────
 * `apply_migration` stores the SQL it was sent as `statements[1]`, and the file on disk is that
 * text with a header bolted on top. Three things have to come off to get back to it, and the
 * second was found the hard way:
 *
 *   1. the contiguous run of `--` lines at the very top, which is the file's own header;
 *   2. the blank line between that header and the SQL — measured 4 Nov 2026, this ONE BYTE was
 *      the entire difference on 68 of 79 files, every one of them reporting a plausible-looking
 *      md5 mismatch until it was found;
 *   3. trailing newlines.
 *
 * A block comment is NOT a header: several migrations open their body with one and production
 * stored it, so the strip stops at the first line that is not `--`.
 *
 * ⚠️ A CARRIAGE RETURN IS A FAILURE, NOT SOMETHING TO NORMALISE AWAY. `.gitattributes` carries
 * `*.sql text eol=lf` precisely so these files check out with LF; a CRLF file would differ on
 * every line ending and the md5 would say nothing about why. It is reported as its own fault.
 */
import { createHash } from 'node:crypto'
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
export const MIGRATIONS = join(HERE, '..', 'supabase', 'migrations')
export const MANIFEST = join(MIGRATIONS, 'applied.md5')

/** The notes `applied.md5` admits in its fourth column. A divergence has to say which it is. */
export const REASONS = {
  're-run-guard':
    'gained drop-if-exists / if-not-exists so the file can replay; does the same thing',
  comments: 'identical SQL once comments and whitespace are normalised away',
  rebuilt: 'read back out of the database with pg_get_functiondef rather than what was sent',
}

export function bodyOf(text) {
  const lines = text.split('\n')
  let i = 0
  while (i < lines.length && lines[i].startsWith('--')) i++
  let body = lines.slice(i).join('\n')
  while (body.startsWith('\n')) body = body.slice(1)
  while (body.endsWith('\n')) body = body.slice(0, -1)
  return body
}

export const md5 = (s) => createHash('md5').update(s, 'utf8').digest('hex')

/** `version  applied-md5  [file-md5  reason]`; `#` comments and blank lines are ignored. */
export function readManifest(text) {
  const rows = new Map()
  for (const raw of text.split('\n')) {
    const line = raw.trim()
    if (!line || line.startsWith('#')) continue
    const [version, applied, file, reason] = line.split(/\s+/)
    rows.set(version, { version, applied, file: file ?? null, reason: reason ?? null })
  }
  return rows
}

export function migrationFiles(dir = MIGRATIONS) {
  return readdirSync(dir)
    .filter((f) => f.endsWith('.sql'))
    .sort()
}

export function check({ dir = MIGRATIONS, manifest = MANIFEST } = {}) {
  const rows = readManifest(readFileSync(manifest, 'utf8'))
  const seen = new Set()
  const out = { matched: [], diverged: [], failed: [], unlisted: [], missing: [] }

  for (const name of migrationFiles(dir)) {
    const version = name.slice(0, 14)
    seen.add(version)
    const raw = readFileSync(join(dir, name), 'utf8')
    const row = rows.get(version)
    if (!row) {
      out.unlisted.push({ name, version })
      continue
    }
    if (raw.includes('\r')) {
      out.failed.push({
        name,
        version,
        why: 'carries CR; it should be LF only, see .gitattributes',
      })
      continue
    }
    const got = md5(bodyOf(raw))
    const want = row.file ?? row.applied
    if (got !== want) {
      out.failed.push({
        name,
        version,
        why: row.file
          ? `changed since it was recorded: ${got}, recorded ${row.file} (${row.reason})`
          : `edited after production applied it: ${got}, production ran ${row.applied}`,
      })
    } else if (row.file) {
      if (row.reason in REASONS) out.diverged.push({ name, version, reason: row.reason })
      else out.failed.push({ name, version, why: `divergence has no reason named: ${row.reason}` })
    } else out.matched.push({ name, version })
  }

  for (const version of rows.keys()) if (!seen.has(version)) out.missing.push({ version })
  return out
}

/**
 * Rewrite the manifest from a dump of production's record — `version md5 [anything]` per line,
 * from the query in the manifest's own header. Existing reasons are carried over; a divergence
 * nobody has explained yet is written `unexplained`, which the check above refuses by name.
 */
export function record({ dump, dir = MIGRATIONS, manifest = MANIFEST }) {
  const applied = new Map(
    dump
      .split('\n')
      .map((l) => l.trim())
      .filter((l) => l && !l.startsWith('#'))
      .map((l) => l.split(/\s+/))
      .map(([version, hash]) => [version, hash]),
  )
  const text = readFileSync(manifest, 'utf8')
  const old = readManifest(text)
  const head = text
    .split('\n')
    .filter((l) => l.startsWith('#') || !l.trim())
    .join('\n')
    .replace(/\n+$/, '')
  const lines = []
  for (const name of migrationFiles(dir)) {
    const version = name.slice(0, 14)
    const ran = applied.get(version)
    if (!ran) continue /* not applied yet, so there is nothing to record about it */
    const got = md5(bodyOf(readFileSync(join(dir, name), 'utf8')))
    if (got === ran) {
      lines.push(`${version}  ${ran}`)
      continue
    }
    const was = old.get(version)
    const reason = was?.file === got && was.reason ? was.reason : 'unexplained'
    lines.push(`${version}  ${ran}  ${got}  ${reason}`)
  }
  writeFileSync(manifest, `${head}\n${lines.join('\n')}\n`)
  return lines.length
}

function main(argv) {
  const at = argv.indexOf('--record')
  if (at !== -1) {
    console.log(`recorded ${record({ dump: readFileSync(argv[at + 1], 'utf8') })} into ${MANIFEST}`)
    return 0
  }
  const r = check()
  console.log(
    `migration md5: ${r.matched.length} match production, ${r.diverged.length} diverge on ` +
      `record, ${r.failed.length} fail, ${r.unlisted.length} not yet recorded`,
  )
  for (const d of r.diverged) console.log(`  . ${d.name}  (${d.reason})`)
  for (const m of r.missing) console.log(`  ? ${m.version} is recorded but has no file here`)
  for (const u of r.unlisted) {
    console.log(`  ? ${u.name} has no line in applied.md5; add one once it is applied`)
  }
  for (const f of r.failed) console.log(`  x ${f.name}\n      ${f.why}`)
  if (r.failed.length) {
    console.log(
      '\nA migration production has already applied must not be edited. Put the fix in a new\n' +
        'timestamped migration. If an edit was deliberate and does not change what the file DOES,\n' +
        'record it: the header of supabase/migrations/applied.md5 says how.',
    )
    return 1
  }
  return 0
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  process.exit(main(process.argv.slice(2)))
}
