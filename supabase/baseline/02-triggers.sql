-- ⚠️ THE SCHEMA DUMP HAS NO TRIGGERS IN IT, AND NOTHING SAID SO. Measured 4 Nov 2026:
-- production carries 24 non-internal triggers on `public` and 0 on `finance`, while
-- `migrations/00000000000000_baseline.sql` contains the string `CREATE TRIGGER` exactly ZERO
-- times. Every other object kind in that file matches production exactly -- 62 tables, 271
-- functions, 88 policies, 62 RLS-enabled tables, 85 foreign keys, 1 view, 1 enum -- so whatever
-- produced it dropped triggers and kept everything else. That is the one shape nothing
-- downstream contradicts: all 24 trigger FUNCTIONS are in the dump, so the schema reads
-- complete, and a grep for the thing that enforces anything comes back empty.
--
-- It is not cosmetic. db-guards run 41954680315, the first run whose guards executed at all,
-- reported `a tier column is writable with no clamp trigger on the table` for five tables and
-- `a stored tier sits above its owner's ceiling: profile_blocks.visibility: 1 row(s)`. Both were
-- TRUE about that database rather than about production: with `chronicle_tier_sync`,
-- `circuit_person_tier_clamp` and the `visibility_certain_forget` pair unattached, nothing
-- clamps a tier on write, and the seed's own block row went in above its owner's ceiling.
--
-- ⚠️ THIS FILE IS DELIBERATELY NOT PART OF THE DUMP. The dump's header says how to regenerate
-- it, and a regeneration is a fresh file: anything hand-written inside one is lost at that
-- moment without a word. So the hand-written pieces sit beside it, here, and are applied around
-- it by `[db.seed] sql_paths` in config.toml. `create or replace trigger` (PG14+) keeps this
-- file idempotent, so a regenerated dump that DOES carry triggers makes this a harmless no-op
-- rather than a conflict.
--
-- Generated by this query against production and checked back against it by md5 rather than by
-- eye, because transcription is the risk when a tool hands over a page of DDL:
--
--   select string_agg(replace(replace(pg_get_triggerdef(tg.oid),
--            'CREATE TRIGGER', 'CREATE OR REPLACE TRIGGER'),
--            'EXECUTE FUNCTION ', 'EXECUTE FUNCTION public.') || ';', E'\n\n'
--            order by c.relname, tg.tgname)
--     from pg_trigger tg
--     join pg_class c on c.oid = tg.tgrelid
--     join pg_namespace n on n.oid = c.relnamespace
--    where not tg.tgisinternal and n.nspname in ('public', 'finance');
--
-- ⚠️ `public.` IS ADDED TO EVERY FUNCTION NAME, AND THE DUMP IS WHY. pg_get_triggerdef writes
-- the function unqualified, because the search_path it is read under has public in it -- while
-- the dump sets `search_path = ''` for its whole session, where an unqualified name resolves to
-- nothing at all. The TABLE names come qualified from pg_get_triggerdef already.

